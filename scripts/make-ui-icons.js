const iconSide = 12;
// One icon pixel is 1u = 2 CSS px = 4 device px on a 2x iPad, so the mask is drawn 1:1 (decision 052).
const scale = 4;
const side = iconSide * scale;

function iconPNG(name, grid) {
  const isGrid = grid.length === iconSide && grid.every((row) => row.length === iconSide && /^[.#]+$/.test(row));
  if (!isGrid) throw new Error(`${name} must be ${iconSide} rows of ${iconSide} "." or "#"`);
  const rgba = new Uint8Array(side * side * 4);
  for (let y = 0; y < side; y++) {
    for (let x = 0; x < side; x++) {
      const isInk = grid[Math.floor(y / scale)][Math.floor(x / scale)] === "#";
      rgba[(y * side + x) * 4 + 3] = isInk ? 255 : 0;
    }
  }
  return encodePNG(side, side, rgba);
}

const folder = new URL("../web/ui/", import.meta.url);
mkdirSync(folder, { recursive: true });
for (const [name, grid] of Object.entries(icons)) {
  writeFileSync(new URL(`${name}.png`, folder), iconPNG(name, grid));
}
