public struct MainPalette: Equatable {
    public static let colorCount = 64

    private var colors = z64.map(Color.init(rgb:))

    public init() {}

    public subscript(index: Int) -> Color {
        get { colors[index & 0x3F] }
        set { colors[index & 0x3F] = newValue }
    }
}

